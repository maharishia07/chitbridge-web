/**
 * cap-cmdb.js — THE CONFIGURATION REGISTER, ON A SCREEN.
 *
 * ── ⭐⭐⭐ THE ASK ────────────────────────────────────────────────────────────────────────────────────────────
 *
 * Athi, 2026-09-12: *"it is like a CMDB kind of, follow the standard set up from the industry"* · *"each screen,
 * each icon and report and so on, entire product catalogue, tie it up with software catalogue and bring
 * visibility"* · *"like testlab, show CMDB as an icon and display for my visibility."*
 *
 * A CMDB (ITIL 4 · ISO/IEC 20000) is the register of configuration items — the things an incident, a change or a
 * test can be raised AGAINST. Every screen in this product is one, and each carries an identifier assigned once
 * and never reused, so a note written today still names the same screen in a year.
 *
 * ── ⚠️ WHAT THIS PANEL IS HONEST ABOUT ──────────────────────────────────────────────────────────────────────
 *
 * ⚠️⚠️ It shows the SCREENS and says plainly that they are the only kind of item registered so far. A CMDB
 * covers every configuration item — controls, reports, capabilities, engines, connectors, environments — and
 * none of those has an identifier yet. Drawing this as "the CMDB" without that sentence would be the most
 * expensive kind of wrong: a register that looks complete.
 *
 * ⚠️ `cases` IS NOT COVERAGE, and the panel repeats it where it is read: the sweep counts a screen's controls
 * against the file that owns them, so five doors sharing cap-chit2.js put their controls on one of them.
 *
 * ── WHERE THE DATA COMES FROM ────────────────────────────────────────────────────────────────────────────────
 *
 * `/app/screens.js`, GENERATED by `C:\dev\screens.cjs` from the live rail and the board. Nothing here counts,
 * derives or guesses — a second place that worked the codes out would disagree with the register within a week,
 * and the whole value of a code is that it means exactly one thing. [[feedback-no-duplicate-functions]]
 */
'use strict';

var CBCMDB = { on: false, q: '', group: '' };

function cmdbEsc(x) {
  return String(x == null ? '' : x).replace(/[&<>"']/g, function (c) {
    return { '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' }[c];
  });
}

function cmdbRows() {
  try { return (window.CBSCREENS && window.CBSCREENS.rows) || []; } catch (_) { return []; }
}

function cmdbToggle() { cmdbSet(!CBCMDB.on); }
function cmdbSet(on) {
  CBCMDB.on = !!on;
  try { localStorage.setItem('cb_cmdb', CBCMDB.on ? '1' : ''); } catch (_) {}
  if (CBCMDB.on) cmdbOpen(); else cmdbClose();
  if (typeof renderApp === 'function') renderApp();
}
function cmdbClose() {
  var h = document.getElementById('cbcmdbhost');
  if (h && h.parentNode) h.parentNode.removeChild(h);
}
function cmdbFilter(k, v) { CBCMDB[k] = v; cmdbPaint(); }

function cmdbOpen() {
  cmdbClose();
  var host = document.createElement('div');
  host.id = 'cbcmdbhost';
  host.innerHTML =
    '<div id="cbcmdbpanel" role="dialog" aria-label="Configuration register" style="position:fixed;right:16px;'
    + 'bottom:16px;width:min(560px,calc(100vw - 32px));max-height:min(70vh,640px);display:flex;'
    + 'flex-direction:column;background:var(--card,#fff);border:1px solid var(--line,#e7e3d8);border-radius:12px;'
    + 'box-shadow:0 10px 34px rgba(0,0,0,.16);z-index:4000;overflow:hidden">'
    /* ⚠️ its own element and classed `mhd`, so minimise leaves something to restore from — the same shape the
       test panel needs for the same reason. */
    + '<div id="cbcmdbhead" class="mhd" style="padding:9px 11px;border-bottom:1px solid var(--line,#e7e3d8);'
    +   'background:var(--paper,#faf8f3);border-radius:12px 12px 0 0"></div>'
    + '<div id="cbcmdbbody" style="overflow:auto;padding:0 11px 11px"></div>'
    + '</div>';
  document.body.appendChild(host);
  try {
    if (typeof makeMovable === 'function') {
      makeMovable(document.getElementById('cbcmdbpanel'), {
        key: 'cb_cmdbpanel', minW: 320, minH: 200, minimise: false,
        /* ⭐ the whole header drags and the window controls sit at the right — the standard title bar, and the
           same one the test panel uses. Nothing invented per panel. */
        dragOn: '#cbcmdbhead', fit: '#cbcmdbbody',
      });
    }
  } catch (_) {}
  cmdbPaint();
}

function cmdbMinimise() {
  var el = document.getElementById('cbcmdbpanel');
  if (el && el._mv && typeof el._mv.toggleMin === 'function') el._mv.toggleMin();
}

function cmdbPaint() {
  var body = document.getElementById('cbcmdbbody'), head = document.getElementById('cbcmdbhead');
  if (!body || !head) return;
  var all = cmdbRows();
  var groups = [];
  all.forEach(function (r) { if (groups.indexOf(r.group) < 0) groups.push(r.group); });

  var q = String(CBCMDB.q || '').toLowerCase();
  var rows = all.filter(function (r) {
    if (CBCMDB.group && r.group !== CBCMDB.group) return false;
    if (!q) return true;
    return (r.code + ' ' + r.path).toLowerCase().indexOf(q) >= 0;
  });

  var ico = 'border:1px solid var(--line,#e7e3d8);background:var(--card,#fff);cursor:pointer;border-radius:7px;'
    + 'width:24px;height:24px;font-size:var(--fs-1);line-height:1;padding:0;color:var(--grey-2,#545A61)';
  head.innerHTML = '<div style="display:flex;align-items:center;gap:6px">'
    + '<b style="font-size:var(--fs-3);white-space:nowrap">\uD83D\uDDC2\uFE0F Configuration register</b>'
    + '<span style="flex:1 1 auto"></span>'
    + '<button title="Minimise" onclick="cmdbMinimise()" style="' + ico + '">\u2013</button>'
    + '<button title="Close" onclick="cmdbSet(false)" style="' + ico + '">\u2715</button>'
    + '</div>'
    + '<div style="display:flex;gap:5px;flex-wrap:wrap;margin-top:7px;align-items:center">'
    +   '<select onchange="cmdbFilter(\'group\',this.value)" style="font-size:var(--fs-2);padding:3px 5px">'
    +     '<option value="">Every menu \u00b7 ' + all.length + '</option>'
    +     groups.map(function (g) {
            var n = all.filter(function (r) { return r.group === g; }).length;
            return '<option value="' + cmdbEsc(g) + '"' + (CBCMDB.group === g ? ' selected' : '') + '>'
              + cmdbEsc(g) + ' \u00b7 ' + n + '</option>';
          }).join('')
    +   '</select>'
    +   '<input value="' + cmdbEsc(CBCMDB.q) + '" oninput="cmdbFilter(\'q\',this.value)" placeholder="code or screen"'
    +     ' style="flex:1 1 140px;font-size:var(--fs-2);padding:3px 6px;border:1px solid var(--line,#e7e3d8);'
    +     'border-radius:7px;background:var(--card,#fff);color:var(--ink)">'
    + '</div>';

  if (!all.length) {
    /* ⚠️ says WHICH empty it is: a missing generated file is a build problem, not an empty register */
    body.innerHTML = '<div style="padding:10px 0;font-size:var(--fs-2);color:var(--note)">'
      + 'The register did not load. <code>/app/screens.js</code> is generated by <code>node screens.cjs</code> '
      + 'and committed \u2014 if it is missing, the build is short of a file rather than the register being empty.</div>';
    return;
  }

  var q2 = 'font-size:var(--fs-1);color:var(--note)';
  var h = '<div style="padding:7px 0 8px;font-size:var(--fs-1);color:var(--grey-2,#545A61);line-height:1.5">'
    + '<b>' + rows.length + '</b> configuration item(s). Every screen carries a code that is <b>assigned once and '
    + 'never reused</b>, so a note quoting it means the same screen in a year.'
    /* ⚠️⚠️ THE SENTENCE THAT KEEPS THIS HONEST. A register that looks complete is worse than a short one. */
    + '<br>\u26a0\ufe0f Screens only, so far. Controls, reports, capabilities, engines and environments are '
    + 'configuration items too and have no identifier yet.'
    + '</div>';

  h += '<table style="width:100%;border-collapse:collapse;font-size:var(--fs-2)">'
    + '<tr style="text-align:start;color:var(--grey-2,#545A61);font-size:var(--fs-1)">'
    + '<th style="text-align:start;padding:3px 6px 3px 0">Code</th>'
    + '<th style="text-align:start;padding:3px 6px">Menu</th>'
    + '<th style="text-align:start;padding:3px 6px">Screen</th>'
    + '<th style="text-align:end;padding:3px 0 3px 6px" title="Cases the board holds for this screen. '
    +   'NOT coverage: the sweep counts a screen\u2019s controls against the file that owns them.">Cases</th></tr>';
  rows.forEach(function (r) {
    h += '<tr style="border-top:1px solid var(--line-2,#efece4)">'
      + '<td style="padding:4px 6px 4px 0"><code style="font-family:\'Space Mono\',ui-monospace,monospace;'
      +   'user-select:all;color:var(--ink)">' + cmdbEsc(r.code) + '</code></td>'
      + '<td style="padding:4px 6px;' + q2 + '">' + cmdbEsc(r.group) + '</td>'
      + '<td style="padding:4px 6px">' + cmdbEsc(r.screen) + '</td>'
      + '<td style="padding:4px 0 4px 6px;text-align:end;font-variant-numeric:tabular-nums;'
      +   (r.cases <= 1 ? q2 : '') + '">' + r.cases + '</td>'
      + '</tr>';
  });
  h += '</table>';
  body.innerHTML = h;
}
