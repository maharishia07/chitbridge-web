#!/usr/bin/env node
/**
 * tools/screen-list.cjs — THE SCREEN LIST, GENERATED FROM THE REGISTER (round SCREEN-ID, 2026-10-14).
 *
 * Athi, 2026-10-14: *"assuming we call one function from another screen, and it has a screen, it should be reflecting"* — so the list says,
 * for every small-app screen and every sheet: code · name · page · how to reach it · which screens OPEN it. A sheet opened from three apps is
 * one row with three openers: visibly one screen.
 *
 * READS the one register: public/app/screen-id.js (the declared small-app and sheet rows, merged into CBSCREENS in the browser) and
 * public/app/screens.js (the workshop's rows, generated by C:/dev/screens.cjs — summarised here by group; C:/dev/SCREENS.md lists them).
 * "Opened from" is DERIVED, never typed: a sheet is opened from every page whose HTML loads the sheet's file (its `<script src>`).
 *
 *   node tools/screen-list.cjs            write docs/SCREEN-LIST.md
 *   node tools/screen-list.cjs --check    exit 1 if docs/SCREEN-LIST.md is not what the register says (e2e/screen-id-guard.cjs runs it)
 *   require('./tools/screen-list.cjs').load(webRoot?)   → { declared, rows, opens: [{ from: code, to: code, page }] } — KG1 (tools/graph) reads this
 */
'use strict';
const fs = require('fs');
const path = require('path');

const WEB = path.join(__dirname, '..');
const OUT = path.join(WEB, 'docs', 'SCREEN-LIST.md');

function evalWindow(file) {
  const w = {};
  new Function('window', 'globalThis', fs.readFileSync(file, 'utf8'))(w, w);
  return w;
}
/** the pages of the product, by the address a person types: index.html is "/" */
function pageFile(root, page) { return page === '/' ? path.join(root, 'index.html') : path.join(root, 'public', page.replace(/^\//, '')); }

function load(root) {
  root = root || WEB;
  const w = evalWindow(path.join(root, 'public', 'app', 'screen-id.js'));
  const declared = w.CBScreenId.DECLARED;
  const rows = w.CBScreenId.rows;
  let workshop = [];
  try { workshop = evalWindow(path.join(root, 'public', 'app', 'screens.js')).CBSCREENS.rows || []; } catch (e) { console.warn('screen-list: public/app/screens.js could not be read - the workshop summary is left out: ' + e.message); }
  /* the openers: every page (a declared app's page, or the workshop) whose HTML loads the sheet's file */
  const pages = declared.apps.map((a) => ({ app: a.app, name: a.name, page: a.page, file: pageFile(root, a.page) }))
    .concat([{ app: null, name: 'the workshop', page: '/app.html', file: path.join(root, 'public', 'app.html'), code: 'APP001' }]);
  const opens = [];
  for (const s of rows.filter((r) => r.kind === 'sheet')) {
    for (const p of pages) {
      let src = '';
      try { src = fs.readFileSync(p.file, 'utf8'); } catch (_) { continue; }
      if (src.indexOf('<script src="/' + s.file + '"') < 0) continue;
      /* every screen of that page can raise the sheet (a bill number, a row, the bell): the edge is from each of them */
      const from = p.app ? rows.filter((r) => r.app === p.app).map((r) => r.code) : [p.code];
      from.forEach((f) => opens.push({ from: f, to: s.code, page: p.page, pageName: p.name }));
    }
  }
  return { declared, rows, opens, workshop };
}

function render(L) {
  const esc = (s) => String(s == null ? '' : s).replace(/\|/g, '\\|');
  const openedFrom = (code) => [...new Set(L.opens.filter((o) => o.to === code).map((o) => o.pageName + ' (' + o.page + ')'))].join(' · ');
  const out = [];
  out.push('# The screen list — GENERATED by tools/screen-list.cjs from the register. Do not edit; run `node tools/screen-list.cjs`.');
  out.push('');
  out.push('Every small-app screen and every sheet has a code (AAA###, assigned once, never reused) and shows it in a chip:');
  out.push('the header for a page or section, the sheet\'s own title row for a sheet. A tap on the chip copies the code.');
  out.push('Register: `public/app/screen-id.js` (declared rows, merged into `CBSCREENS`) + `public/app/screens.js` (the workshop).');
  out.push('');
  out.push('## Small apps');
  out.push('');
  out.push('| Code | Screen | App | Page | How to reach it |');
  out.push('|---|---|---|---|---|');
  for (const r of L.rows.filter((x) => x.kind !== 'sheet')) out.push('| ' + [r.code, r.screen, r.appName, r.page, r.reach].map(esc).join(' | ') + ' |');
  out.push('');
  out.push('## Sheets — one screen, wherever it is opened from');
  out.push('');
  out.push('| Code | Screen | Painted by | How to reach it | Opened from |');
  out.push('|---|---|---|---|---|');
  for (const r of L.rows.filter((x) => x.kind === 'sheet')) out.push('| ' + [r.code, r.screen, r.file, r.reach, openedFrom(r.code) || '—'].map(esc).join(' | ') + ' |');
  out.push('');
  const g = {};
  L.workshop.forEach((r) => { const k = r.group + ' (' + r.code.slice(0, 3) + ')'; g[k] = (g[k] || 0) + 1; });
  out.push('## The workshop (app.html) — ' + L.workshop.length + ' rows in public/app/screens.js, listed in C:/dev/SCREENS.md');
  out.push('');
  out.push(Object.keys(g).map((k) => k + ' ' + g[k]).join(' · '));
  out.push('');
  return out.join('\n');
}

if (require.main === module) {
  const text = render(load());
  if (process.argv.includes('--check')) {
    const now = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8') : '';
    if (now !== text) { console.error('docs/SCREEN-LIST.md is not what the register says - run: node tools/screen-list.cjs'); process.exit(1); }
    console.log('docs/SCREEN-LIST.md matches the register');
  } else {
    fs.writeFileSync(OUT, text);
    console.log('wrote docs/SCREEN-LIST.md');
  }
}
module.exports = { load, render };
