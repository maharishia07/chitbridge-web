#!/usr/bin/env node
'use strict';
/**
 * tools/seams.cjs — WHAT ALREADY DOES THIS? The index to read before building, and the drift check for docs/SEAMS.md.
 *
 * OWNS      the seam index (a function DEFINED in one file and CALLED from another is a reuse point, by demonstration: nobody keeps the
 *           list), its search, its writer for docs/SEAMS.md in web · api · engines, and its drift check (DOC-68, docs truth).
 * CALLED BY C:/dev/seams.cjs (a shim, so `node C:/dev/seams.cjs <word>` still works) · the `seams-drift` CI job of web, api and engines
 *           (api and engines run this file from a web checkout: one copy of the logic).
 * FLOW      argv ──▶ scan the web side and/or the api side ──▶ search | index | --write | --check ──▶ stdout / docs/SEAMS.md / exit code
 * CARD      29-qa-test-tooling-ux-locale-and-design-system/seams-index
 *
 * Athi, 2026-08-24, after the second reinvention in two days: "I would assume you know what you have built and know to reuse."
 * `inventory.cjs` says what KIND of file each thing is; this says what already does the job. The list of seams used once is where the next
 * duplicate is born, because a thing used once looks private and gets rebuilt.
 *
 *   node tools/seams.cjs                              the index, most-reused first
 *   node tools/seams.cjs catalogue                    everything whose name, purpose or file mentions every word
 *   node tools/seams.cjs --write                      refresh C:/dev/SEAMS.md AND docs/SEAMS.md in web, api, engines
 *   node tools/seams.cjs --check --repo web|api|engines   exit 1 and print the stale lines of the docs/SEAMS.md in the current folder
 *
 * Roots default to the main checkouts; SEAMS_ROOT_<WEB|API|ENGINES> point at another checkout (a worktree).
 */
const fs = require('fs');
const path = require('path');

const FUNCTION_DEFINITION = /^[ \t]*(?:async[ \t]+)?function[ \t]+([A-Za-z_$][\w$]*)[ \t]*\(/gm;
const MODULE_DEFINITION = /^[ \t]*(?:var|const|let)[ \t]+([A-Z][\w$]*)[ \t]*=[ \t]*\(?[ \t]*(?:function|\(\)[ \t]*=>)/gm;
const GENERATED_MARK = '<!-- GENERATED by C:/dev/seams.cjs --write.';
const AMBIGUOUS_MARK = /same-name files[^:]*: ?(.*) -->/;
const TABLE_ROW = /^\| (\d+) \| `([^`]+)` \| `([^`]+)` \| (.*) \|$/;
const INDEX_ROWS = 200;
const MIN_NAME_LENGTH = 4;

/* ── what to read ─────────────────────────────────────────────────────────────────────────────────────────── */

/** the folder of one repo: the environment override, else the checkout we are checking from, else the main checkout */
function repoRoot(side, checking) {
  return process.env['SEAMS_ROOT_' + side.toUpperCase()] || (side === checking ? process.cwd() : 'C:/dev/chitbridge-' + side);
}

/** the web files that define or call functions: the shell page and every public/app script */
function webFiles(root) {
  const publicDir = path.join(root, 'public');
  const found = [path.join(publicDir, 'app.html')];
  for (const name of fs.readdirSync(path.join(publicDir, 'app'))) {
    if (name.endsWith('.js')) found.push(path.join(publicDir, 'app', name));
  }
  return found;
}

/** the api files that define or call functions: lib, routes and middleware */
function apiFiles(root) {
  const found = [];
  for (const folder of ['lib', 'routes', 'middleware']) {
    const dir = path.join(root, folder);
    if (!fs.existsSync(dir)) continue;
    for (const name of fs.readdirSync(dir)) if (name.endsWith('.js')) found.push(path.join(dir, name));
  }
  return found;
}

/* ── definitions ──────────────────────────────────────────────────────────────────────────────────────────── */

/** one comment line without its comment marks, or '' for a rule line */
function commentText(line) {
  const text = line.replace(/^\s*(\/\*+|\*+\/?|\/\/)\s?/, '').replace(/\s*\*\/\s*$/, '').trim();
  return /^[─—=*\-·]{3,}$/.test(text) ? '' : text;
}

/** the purpose line: the nearest preceding comment's first real sentence; '' is honest — a seam with no comment tells you only its name */
function purposeAbove(source, position) {
  const before = source.slice(Math.max(0, position - 1600), position).split(/\r?\n/);
  for (let index = before.length - 2; index >= 0 && index > before.length - 30; index--) {
    if (/^\s*(\}|\)|;)/.test(before[index])) break; // walked out of the comment into code
    const text = commentText(before[index]);
    if (/^[A-Za-z⭐⚠️`]/.test(text) && text.length > 12) {
      return text.replace(/^[⭐⚠️\s]+/, '').replace(/\*\*/g, '').split(/(?<=[.:—])\s/)[0].slice(0, 110);
    }
  }
  return '';
}

/** every [name, position] one source defines as a function or a capitalised module */
function definitionsIn(source) {
  const found = [];
  for (const pattern of [FUNCTION_DEFINITION, MODULE_DEFINITION]) {
    pattern.lastIndex = 0;
    let match;
    while ((match = pattern.exec(source))) found.push([match[1], match.index]);
  }
  return found;
}

/** name → { file, purpose } for every function a file defines (the first definition wins) */
function collectDefinitions(texts) {
  const definitions = new Map();
  for (const [file, source] of texts) {
    for (const [name, position] of definitionsIn(source)) {
      if (!definitions.has(name)) definitions.set(name, { file, purpose: purposeAbove(source, position) });
    }
  }
  return definitions;
}

/** the base names of the OTHER files that call the function — files, not call sites: ten calls in one screen is a local helper */
function usersOf(name, definingFile, texts) {
  const call = new RegExp('(?:^|[^\\w$.])' + name.replace(/\$/g, '\\$') + '\\s*[(.]');
  const users = [];
  for (const [file, source] of texts) {
    if (file !== definingFile && call.test(source)) users.push(path.basename(file));
  }
  return users;
}

/** every function of one side, with the files that use it */
function scan(files, label) {
  const texts = new Map(files.map((file) => [file, fs.readFileSync(file, 'utf8')]));
  const rows = [];
  for (const [name, definition] of collectDefinitions(texts)) {
    if (name.length < MIN_NAME_LENGTH) continue;
    rows.push({ name, from: path.basename(definition.file), users: usersOf(name, definition.file, texts), purpose: definition.purpose, label });
  }
  return rows;
}

/** the table row as --write prints it (one place, so --check compares exactly what --write would have written) */
function rowText(row) {
  return '| ' + row.users.length + ' | `' + row.name + '` | `' + row.from + '` | ' + (row.purpose || '').replace(/\|/g, '·') + ' |';
}

/** file names that exist on BOTH sides: a table row naming one cannot be told apart by the name alone */
function ambiguousNames(rows) {
  const sidesOf = new Map();
  for (const row of rows) sidesOf.set(row.from, (sidesOf.get(row.from) || new Set()).add(row.label));
  return [...sidesOf].filter(([, sides]) => sides.size > 1).map(([file]) => file).sort();
}

/* ── the report ───────────────────────────────────────────────────────────────────────────────────────────── */

/** every word must appear in the name, the purpose or the file name — words, not phrases, is what a person types */
function matchesWords(row, words) {
  const haystacks = [row.name, row.purpose || '', row.from].map((text) => text.toLowerCase());
  return words.every((word) => haystacks.some((text) => text.includes(word)));
}

/** the words after a search: up to 40 hits, shared first */
function printSearch(needle, shared, once) {
  const words = needle.split(/\s+/).filter(Boolean);
  console.log('\n══ WHAT ALREADY DOES "' + needle + '" ══\n');
  const hits = shared.filter((row) => matchesWords(row, words)).concat(once.filter((row) => matchesWords(row, words)));
  if (!hits.length) console.log('  nothing — this may genuinely be new\n');
  for (const row of hits.slice(0, 40)) {
    const used = row.users.length ? 'used by ' + row.users.length + ': ' + row.users.slice(0, 4).join(', ') : 'used only where it is defined';
    console.log('  ' + row.name.padEnd(26) + row.from.padEnd(22) + used);
    if (row.purpose) console.log('      ' + row.purpose);
  }
  console.log('');
}

/** the index, most-reused first, with the two counts */
function printIndex(shared, once) {
  console.log('\n══ SHARED SEAMS — defined in one file, called from another ══\n');
  for (const row of shared.slice(0, 60)) {
    console.log('  ' + String(row.users.length).padStart(3) + '  ' + row.name.padEnd(26) + row.from.padEnd(22) + row.users.slice(0, 5).join(', '));
    if (row.purpose) console.log('       ' + row.purpose);
  }
  console.log('\n  ' + shared.length + ' seam(s) · ' + once.length + ' defined-and-used-once');
  console.log('  ⚠️ The second number is where the next duplicate is born: a thing used once looks private.\n');
}

/** the text of docs/SEAMS.md: header, the same-name files, the table of the most reused seams */
function indexMarkdown(rows, shared) {
  return [
    '# Seams — what is already reusable',
    '',
    GENERATED_MARK + ' A seam is a function DEFINED in one file and CALLED from',
    '     another: the calls are the evidence, so nothing here has to be kept current by hand. -->',
    '<!-- same-name files in web and api (--check cannot tell whose row it is, so it skips them): ' + ambiguousNames(rows).join(' ') + ' -->',
    '',
    '⭐ **Read this before building anything that sounds like it might exist.** `inventory.cjs` says what kind',
    'of file each thing is; this says what already does the job.',
    '',
    '| used by | name | defined in | what it is for |',
    '|---|---|---|---|'
  ].concat(shared.slice(0, INDEX_ROWS).map(rowText)).join('\n') + '\n';
}

/** write the same index into C:/dev and into each repo's docs folder (cloud sessions read docs/SEAMS.md in their own clone) */
function writeIndex(rows, shared) {
  const text = indexMarkdown(rows, shared);
  const targets = ['C:/dev/SEAMS.md'].concat(['web', 'api', 'engines'].map((side) => repoRoot(side, '') + '/docs/SEAMS.md'));
  for (const target of targets) {
    if (!fs.existsSync(path.dirname(target))) {
      console.log('  skipped (no folder): ' + target);
      continue;
    }
    fs.writeFileSync(target, text);
    console.log('  → ' + target + ' (' + shared.length + ' seams)');
  }
  console.log('');
}

/* ── the drift check ──────────────────────────────────────────────────────────────────────────────────────── */

/** the rows of the table in a docs/SEAMS.md text */
function tableRows(text) {
  return text.split('\n').map((line) => TABLE_ROW.exec(line)).filter(Boolean)
    .map((found) => ({ users: Number(found[1]), name: found[2], from: found[3], line: found[0] }));
}

/** the doc rows of OUR side that no longer match the code: changed counts or purposes, functions gone or no longer shared */
function staleOwnRows(docRows, ownRows, skipped) {
  const ownFiles = new Set(ownRows.map((row) => row.from).filter((file) => !skipped.has(file)));
  const byKey = new Map(ownRows.map((row) => [row.name + '|' + row.from, row]));
  const stale = [];
  for (const docRow of docRows) {
    if (!ownFiles.has(docRow.from)) continue; // the other side's row: judged in the other repo
    const current = byKey.get(docRow.name + '|' + docRow.from);
    if (!current || !current.users.length) stale.push('- gone or no longer shared: ' + docRow.line);
    else if (rowText(current) !== docRow.line) stale.push('- changed: ' + docRow.line + '\n    now: ' + rowText(current));
  }
  return stale;
}

/** seams used more widely than the table's weakest row that the table does not list (a less-used new seam is not drift) */
function missingFromTable(docRows, shared) {
  const weakest = Math.min.apply(null, docRows.map((docRow) => docRow.users));
  const listed = new Set(docRows.map((docRow) => docRow.name + '|' + docRow.from));
  return shared.filter((row) => row.users.length > weakest && !listed.has(row.name + '|' + row.from)).map((row) => '- missing: ' + rowText(row));
}

/** the checked side's rows, or null when the side is unknown / owns none */
function ownSideRows(side) {
  if (side === 'web') return scan(webFiles(repoRoot('web', side)), 'web');
  if (side === 'api') return scan(apiFiles(repoRoot('api', side)), 'api');
  return null;
}

/** judge docs/SEAMS.md of the folder we run in against the code of its own side; returns the process exit code */
function runCheck(side) {
  const doc = path.join(process.cwd(), 'docs', 'SEAMS.md');
  if (!fs.existsSync(doc)) return reportLine('seams --check: missing ' + doc);
  const text = fs.readFileSync(doc, 'utf8').split('\r\n').join('\n');
  if (!text.includes(GENERATED_MARK)) return reportLine('seams --check: ' + doc + ' has lost its GENERATED header - regenerate: node C:/dev/seams.cjs --write');
  if (side === 'engines') return reportLine('seams --check (engines): owns no rows; header ok', 0);
  const ownRows = ownSideRows(side);
  if (!ownRows) return reportLine('seams --check: pass --repo web|api|engines');
  const skipped = new Set(((AMBIGUOUS_MARK.exec(text) || [])[1] || '').split(' ').filter(Boolean));
  const docRows = tableRows(text);
  const shared = ownRows.filter((row) => row.users.length);
  const stale = staleOwnRows(docRows, ownRows, skipped).concat(missingFromTable(docRows, shared));
  if (!stale.length) return reportLine('seams --check (' + side + '): docs/SEAMS.md matches the code', 0);
  reportLine('seams --check (' + side + '): ' + stale.length + ' stale line(s) in ' + doc + ' - run: node C:/dev/seams.cjs --write (from an LF checkout)');
  stale.slice(0, 40).forEach((line) => console.log(line));
  return 1;
}

/** print one line and return the exit code (1 unless told otherwise) */
function reportLine(line, code) {
  console.log(line);
  return code === undefined ? 1 : code;
}

/* ── the command line ─────────────────────────────────────────────────────────────────────────────────────── */

/** argv → { check, write, side, needle } */
function parseArguments(argv) {
  const sideAt = argv.indexOf('--repo');
  const words = argv.filter((word, index) => !['--write', '--check', '--repo'].includes(word) && argv[index - 1] !== '--repo');
  return {
    check: argv.includes('--check'),
    write: argv.includes('--write'),
    side: sideAt > -1 ? argv[sideAt + 1] : '',
    needle: words.join(' ').toLowerCase().trim()
  };
}

/** run the command; returns the exit code */
function main(argv) {
  const options = parseArguments(argv);
  if (options.check) return runCheck(options.side);
  const rows = scan(webFiles(repoRoot('web', '')), 'web').concat(scan(apiFiles(repoRoot('api', '')), 'api'));
  const shared = rows.filter((row) => row.users.length >= 1).sort((first, second) => second.users.length - first.users.length);
  const once = rows.filter((row) => row.users.length === 0);
  if (options.needle) printSearch(options.needle, shared, once);
  else printIndex(shared, once);
  if (options.write) writeIndex(rows, shared);
  return 0;
}

if (require.main === module) process.exitCode = main(process.argv.slice(2));

module.exports = { main, parseArguments, scan, rowText, tableRows, staleOwnRows, missingFromTable, matchesWords, purposeAbove };
