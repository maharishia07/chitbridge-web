#!/usr/bin/env node
'use strict';
/**
 * OWNS  e2e/gen-tokens.cjs + public/tokens.json: the ONE token file in the W3C Design Tokens Community Group format (Format Module 2025.10),
 *       generated from the CSS custom properties the app already has (app.html :root, first definition wins) and the 16 themes of the
 *       engine (public/engine/screen.js APP_THEMES). The CSS stays the source; this file is the export other tools read.
 * CALLED BY hand and CI (static, no browser):  node e2e/gen-tokens.cjs --check   (exit 1 when public/tokens.json is stale)
 *                                              node e2e/gen-tokens.cjs           (rewrite it)
 * CARD  29-qa-test-tooling-ux-locale-and-design-system/themes-contrast-accessibility
 * Shape: { color: { base: { <name>: {$type:'color',$value} }, themes: { <key>: { <name>: ... } } }, dimension: { base: {...} } }.
 * An alias (`var(--x)`) becomes a DTCG reference "{color.base.x}". Values that are neither a colour nor a px size (shadows, gradients,
 * font stacks) are not tokens of a DTCG type here and are left to the CSS. The base parsing is the same rule as e2e/a11y-contrast.cjs baseTokens().
 */
const fs = require('fs'), path = require('path');
const ROOT = path.join(__dirname, '..');
const OUT = path.join(ROOT, 'public', 'tokens.json');
const src = fs.readFileSync(path.join(ROOT, 'public', 'app.html'), 'utf8');

const COLOUR = /^(#[0-9a-f]{3,8}|rgba?\([^)]*\)|hsla?\([^)]*\))$/i;
const PX = /^(-?\d+(?:\.\d+)?)px$/;

function base() {
  const out = {}; const css = src.slice(0, src.indexOf('</style>') > 0 ? src.indexOf('</style>') : 200000);
  const re = /(--[a-z0-9-]+)\s*:\s*([^;{}]+)[;}]/gi; let m;
  while ((m = re.exec(css))) { if (!(m[1] in out)) out[m[1]] = m[2].trim(); }
  return out;
}
function themes() {
  globalThis.window = globalThis; require(path.join(ROOT, 'public', 'engine', 'screen.js'));
  return globalThis.CBScreen.APP_THEMES;
}
/** one CSS value to a DTCG token, or null when it has no DTCG type here */
function tok(v, colourNames) {
  const a = /^var\(\s*(--[a-z0-9-]+)\s*\)$/i.exec(v);
  if (a) return colourNames.has(a[1]) ? { $type: 'color', $value: '{color.base.' + a[1].slice(2) + '}' } : null;
  if (COLOUR.test(v)) return { $type: 'color', $value: v };
  return null;
}
function build() {
  const B = base(), names = new Set(Object.keys(B).filter((k) => COLOUR.test(B[k])));
  const color = { base: {}, themes: {} }, dimension = { base: {} };
  for (const k of Object.keys(B).sort()) {
    const t = tok(B[k], names), p = PX.exec(B[k]);
    if (t) color.base[k.slice(2)] = t;
    else if (p) dimension.base[k.slice(2)] = { $type: 'dimension', $value: { value: +p[1], unit: 'px' } };
  }
  const T = themes();
  for (const key of Object.keys(T).sort()) {
    const g = {}, vars = T[key].vars || {};
    for (const k of Object.keys(vars).sort()) { const t = tok(String(vars[k]).trim(), names); if (t) g[k.slice(2)] = t; }
    color.themes[key] = g;
  }
  return { $description: 'Generated by e2e/gen-tokens.cjs from app.html :root and engine APP_THEMES. Do not edit; edit the CSS and regenerate. Format: W3C Design Tokens Community Group, Format Module 2025.10 (a community-group final report, not a W3C Recommendation).', color, dimension };
}
const text = JSON.stringify(build(), null, 2) + '\n';
if (process.argv.includes('--check')) {
  const cur = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8').replace(/\r\n/g, '\n') : '';
  if (cur !== text) { console.error('gen-tokens: public/tokens.json is stale — run: node e2e/gen-tokens.cjs'); process.exit(1); }
  const o = JSON.parse(cur), nb = Object.keys(o.color.base).length, nt = Object.keys(o.color.themes).length;
  /* every reference must resolve inside the file */
  let bad = 0; (function walk(n) { for (const k in n) { const v = n[k]; if (v && typeof v === 'object') { if ('$value' in v) { if (typeof v.$value === 'string' && /^\{.*\}$/.test(v.$value) && !v.$value.slice(1, -1).split('.').reduce((a, p) => a && a[p], o)) { bad++; console.error('unresolved ' + v.$value); } } else walk(v); } } })(o);
  if (bad) process.exit(1);
  console.log('gen-tokens: ok — tokens.json current, ' + nb + ' base colours, ' + nt + ' themes, every reference resolves');
} else { fs.writeFileSync(OUT, text); console.log('gen-tokens: wrote ' + OUT); }
