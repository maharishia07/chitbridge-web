/**
 * cap-cmdb.js — THE CONFIGURATION REGISTER, ON A SCREEN.
 *
 * ── ⭐⭐⭐ THE ASK ────────────────────────────────────────────────────────────────────────────────────────────
 *
 * Athi, 2026-09-12: *"it is like a CMDB kind of, follow the standard set up from the industry"* · *"each screen,
 * each icon and report and so on, entire product catalogue, tie it up with software catalogue and bring
 * visibility"* · *"like testlab, show CMDB as an icon and display for my visibility."*
 *
 * A CMDB (ITIL 4 · ISO/IEC 20000) is the register of configuration items — the things an incident, a change or a
 * test can be raised AGAINST. Every screen in this product is one, and each carries an identifier assigned once
 * and never reused, so a note written today still names the same screen in a year.
 *
 * ── ⚠️ WHAT THIS PANEL IS HONEST ABOUT ──────────────────────────────────────────────────────────────────────
 *
 * ⚠️⚠️ It shows the SCREENS and says plainly that they are the only kind of item registered so far. A CMDB
 * covers every configuration item — controls, reports, capabilities, engines, connectors, environments — and
 * none of those has an identifier yet. Drawing this as "the CMDB" without that sentence would be the most
 * expensive kind of wrong: a register that looks complete.
 *
 * ⚠️ `cases` IS NOT COVERAGE, and the panel repeats it where it is read: the sweep counts a screen's controls
 * against the file that owns them, so five doors sharing cap-chit2.js put their controls on one of them.
 *
 * ── WHERE THE DATA COMES FROM ────────────────────────────────────────────────────────────────────────────────
 *
 * `/app/screens.js`, GENERATED by `screens.cjs` from the live rail and the board. Nothing here counts,
 * derives or guesses — a second place that worked the codes out would disagree with the register within a week,
 * and the whole value of a code is that it means exactly one thing. [[feedback-no-duplicate-functions]]
 */
'use strict';

var CBCMDB = { on: false, q: '', group: '', kind: 'SCREEN' };

/**
 * ⭐⭐ THE SOFTWARE HALF OF THE REGISTER — `window.CBASSETS`, generated by assets.cjs.
 * Athi, 2026-09-12: *"software life cycle with all the asset register etc, if you can make it the way it is
 * supposed to be"* · *"tie it up with software catalogue and bring visibility."*
 *
 * ⚠️ `stage` is what the FILE declares about itself (`@stage tested|proven|held|poc`). Absent means **not
 * stated**, and the panel prints those words rather than guessing: "probably tested, it has a test file" is
 * exactly the inference that turns a register into a comfort blanket.
 */
function cmdbAssets() {
  try { return (window.CBASSETS && window.CBASSETS.rows) || []; } catch (_) { return []; }
}
function cmdbDrawnBy(code) {
  try { return (window.CBASSETS && window.CBASSETS.drawnBy && window.CBASSETS.drawnBy[code]) || null; }
  catch (_) { return null; }
}

function cmdbEsc(x) {
  return String(x == null ? '' : x).replace(/[&<>"']/g, function (c) {
    return { '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' }[c];
  });
}

/**
 * ⚠⚠ SCREENS AND POPUPS ARE BOTH IN THE REGISTER AND MUST NOT SHARE A LIST. 84 dialogs dropped into a list of
 * 48 screens would bury the screens and make the count meaningless — they are different kinds of thing and a
 * person is looking for one or the other, never both.
 */
function cmdbRows() {
  try {
    return ((window.CBSCREENS && window.CBSCREENS.rows) || [])
      .filter(function (r) {
        return r.group !== 'Popup' && r.group !== 'Control' && r.group !== 'Panel';
      });
  } catch (_) { return []; }
}
/**
 * ⭐ THE CONTROLS. Athi, 2026-09-12: *"each screen, each icon and report… all those should be in CMDB."*
 * ⚠️ 151 of them carry no readable name and deliberately have NO code — a tester cannot be given a label that
 * appears nowhere on their screen, so the register says so instead of inventing one.
 */
function cmdbControls() {
  try {
    return ((window.CBSCREENS && window.CBSCREENS.rows) || [])
      .filter(function (r) { return r.group === 'Control'; });
  } catch (_) { return []; }
}
/**
 * ⭐ THE PANELS. Athi, 2026-09-12: *"now the same way each panel has to get the name."*
 * ⚠️ Their own kind for the same reason popups have one: a panel is not a screen. It floats OVER whatever
 * screen you are on and stays there, so five of them inside a list of forty-eight screens would make the
 * screen count wrong and answer a question nobody asked.
 */
function cmdbPanels() {
  try { return ((window.CBSCREENS && window.CBSCREENS.rows) || []).filter(function (r) { return r.group === 'Panel'; }); }
  catch (_) { return []; }
}
/**
 * ⭐⭐ AND THE WITHDRAWN CODES, WHICH IS WHERE THE QUESTION ACTUALLY GETS ASKED. Athi asked "which one is
 * DTL002?" hours after it was withdrawn. A register that can only list what currently exists cannot answer
 * that, and a code you cannot look up is a code people stop quoting.
 */
function cmdbGone() {
  try { return (window.CBSCREENS && window.CBSCREENS.withdrawn) || []; } catch (_) { return []; }
}
function cmdbPopups() {
  try { return ((window.CBSCREENS && window.CBSCREENS.rows) || []).filter(function (r) { return r.group === 'Popup'; }); }
  catch (_) { return []; }
}

function cmdbToggle() { cmdbSet(!CBCMDB.on); }
function cmdbSet(on) {
  CBCMDB.on = !!on;
  try { localStorage.setItem('cb_cmdb', CBCMDB.on ? '1' : ''); } catch (_) {}
  if (CBCMDB.on) cmdbOpen(); else cmdbClose();
  if (typeof renderApp === 'function') renderApp();
}
function cmdbClose() {
  var h = document.getElementById('cbcmdbhost');
  if (h && h.parentNode) h.parentNode.removeChild(h);
}
function cmdbFilter(k, v) { CBCMDB[k] = v; cmdbPaint(); }

function cmdbOpen() {
  cmdbClose();
  var host = document.createElement('div');
  host.id = 'cbcmdbhost';
  host.innerHTML =
    '<div id="cbcmdbpanel" role="dialog" aria-label="Configuration register" style="position:fixed;right:16px;'
    + 'bottom:16px;width:min(560px,calc(100vw - 32px));max-height:min(70vh,640px);display:flex;'
    + 'flex-direction:column;background:var(--card,#fff);border:1px solid var(--line,#e7e3d8);border-radius:12px;'
    + 'box-shadow:0 10px 34px rgba(0,0,0,.16);z-index:4000;overflow:hidden">'
    /* ⚠️ its own element and classed `mhd`, so minimise leaves something to restore from — the same shape the
       test panel needs for the same reason. */
    + '<div id="cbcmdbhead" class="mhd" style="padding:9px 11px;border-bottom:1px solid var(--line,#e7e3d8);'
    +   'background:var(--paper,#faf8f3);border-radius:12px 12px 0 0"></div>'
    + '<div id="cbcmdbbody" style="overflow:auto;padding:0 11px 11px"></div>'
    + '</div>';
  document.body.appendChild(host);
  try {
    if (typeof makeMovable === 'function') {
      makeMovable(document.getElementById('cbcmdbpanel'), {
        key: 'cb_cmdbpanel', minW: 320, minH: 200, minimise: false,
        /* ⭐ the whole header drags and the window controls sit at the right — the standard title bar, and the
           same one the test panel uses. Nothing invented per panel. */
        dragOn: '#cbcmdbhead', fit: '#cbcmdbbody',
      });
    }
  } catch (_) {}
  cmdbPaint();
}

function cmdbMinimise() {
  var el = document.getElementById('cbcmdbpanel');
  if (el && el._mv && typeof el._mv.toggleMin === 'function') el._mv.toggleMin();
}

/** the four kinds, with their counts — a switch that cannot say how many is a switch you press to find out */
var PLURAL = { CAP: 'Capabilities', ENG: 'Engines', API: 'Routes' };
function cmdbKindsHTML() {
  var A = cmdbAssets();
  var kinds = [['SCREEN', 'Screens', cmdbRows().length]];
  if (cmdbPopups().length) kinds.push(['POPUP', 'Popups', cmdbPopups().length]);
  if (cmdbPanels().length) kinds.push(['PANEL', 'Panels', cmdbPanels().length]);
  if (cmdbControls().length) kinds.push(['CONTROL', 'Controls', cmdbControls().length]);
  ['CAP', 'ENG', 'API'].forEach(function (k) {
    var n = A.filter(function (x) { return x.type === k; });
    /* ⚠ A PLURAL IS NOT A NOUN PLUS S. It read "Capabilitys" the first time this was shown to Athi — small,
       but a register whose own labels are wrong is not one anybody trusts with a number. Declared per type. */
    if (n.length) kinds.push([k, PLURAL[k] || (n[0].kind + 's'), n.length]);
  });
  /* ⚠️ LAST, and only when there are any: withdrawn codes are a lookup, not a list anybody browses. Putting
     them beside the live kinds would suggest they are things you can still open. */
  if (cmdbGone().length) kinds.push(['GONE', 'Withdrawn', cmdbGone().length]);
  var base = 'font:inherit;font-size:var(--fs-1);padding:2px 8px;border:1px solid var(--line,#e7e3d8);'
    + 'border-radius:7px;cursor:pointer;';
  return kinds.map(function (k) {
    var on = CBCMDB.kind === k[0];
    return '<button onclick="cmdbFilter(\'kind\',\'' + k[0] + '\')" style="' + base
      + (on ? 'background:var(--grey-2,#545A61);color:#fff;border-color:var(--grey-2,#545A61)'
            : 'background:var(--card,#fff);color:var(--grey-2,#545A61)') + '">'
      + cmdbEsc(k[1]) + ' <b>' + k[2] + '</b></button>';
  }).join('');
}

