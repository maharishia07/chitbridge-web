#!/usr/bin/env node
// @type: unit
/**
 * doc-5-seams-write.test.cjs — DOC-5 + DOC-68 (proof 2026-11-14): `seams.cjs --write` refreshes the docs/SEAMS.md of the repo it runs from (and no sibling's),
 * and `--check` fails on a stale doc and passes on a fresh one (the SEAMS half of the docs-truth line); gen-modules-doc.cjs --check does the same for MODULES.md.
 * Everything runs in throw-away fixture folders (SEAMS_ROOT_WEB / SEAMS_ROOT_API point at them), so no checkout is read or written.
 * CALLED BY .github/workflows/ci.yml (Offline guards). No browser, no network, no sibling repo.
 *   node tests/doc-5-seams-write.test.cjs
 */
'use strict';
const assert = require('assert');
const fs = require('fs');
const os = require('os');
const path = require('path');
const { spawnSync } = require('child_process');

const SEAMS = path.join(__dirname, '..', 'tools', 'seams.cjs');
const MODULES = path.join(__dirname, '..', 'tools', 'gen-modules-doc.cjs');
let pass = 0;
const ok = (condition, name) => { assert(condition, name); pass++; console.log('  ok  ' + name); };
const put = (file, text) => { fs.mkdirSync(path.dirname(file), { recursive: true }); fs.writeFileSync(file, text); };
const tool = (script, args, cwd, env) => spawnSync('node', [script].concat(args), { cwd, env: Object.assign({}, process.env, env || {}), encoding: 'utf8' });

const base = fs.mkdtempSync(path.join(os.tmpdir(), 'doc5-'));
const web = path.join(base, 'web'), api = path.join(base, 'api'), engines = path.join(base, 'engines');
// a web repo with one seam: freightTotal is defined in one script and called from two others
put(path.join(web, 'public', 'app.html'), '<html></html>\n');
put(path.join(web, 'public', 'app', 'cart.js'), '// the cart\nfunction freightTotal(lines) { return lines.length; }\n');
put(path.join(web, 'public', 'app', 'a.js'), 'var x = freightTotal([1]);\n');
put(path.join(web, 'public', 'app', 'b.js'), 'var y = freightTotal([2]);\n');
put(path.join(api, 'routes', 'noop.js'), 'module.exports = {};\n');
put(path.join(api, 'docs', 'KEEP.md'), 'the sibling doc, never touched\n');
fs.mkdirSync(path.join(web, 'docs'), { recursive: true });
fs.mkdirSync(path.join(engines, 'src'), { recursive: true });
fs.mkdirSync(path.join(engines, 'docs'), { recursive: true });
const env = { SEAMS_ROOT_WEB: web, SEAMS_ROOT_API: api };

// DOC-5: --write from the web root writes web/docs/SEAMS.md and nothing else
const sharedDoc = 'C:/dev/SEAMS.md';
const sharedBefore = fs.existsSync(sharedDoc) ? fs.statSync(sharedDoc).mtimeMs : null;
const written = tool(SEAMS, ['--write', '--repo', 'web'], web, env);
ok(written.status === 0, 'DOC-5: --write from a repo root exits 0');
const doc = path.join(web, 'docs', 'SEAMS.md');
ok(fs.existsSync(doc) && /GENERATED by C:\/dev\/seams\.cjs --write/.test(fs.readFileSync(doc, 'utf8')) && /`freightTotal`/.test(fs.readFileSync(doc, 'utf8')), "DOC-5: --write refreshes THIS repo's docs/SEAMS.md (the seam is in its table)");
ok(!fs.existsSync(path.join(api, 'docs', 'SEAMS.md')) && fs.readFileSync(path.join(api, 'docs', 'KEEP.md'), 'utf8') === 'the sibling doc, never touched\n', "DOC-5: a sibling repo's docs are not written");
ok(sharedBefore === (fs.existsSync(sharedDoc) ? fs.statSync(sharedDoc).mtimeMs : null), 'DOC-5: C:/dev/SEAMS.md is not what --write refreshes');
const elsewhere = tool(SEAMS, ['--write'], base, env);
ok(elsewhere.status === 1 && !fs.existsSync(path.join(base, 'docs')), 'DOC-5: --write from a folder that is no repo root writes nothing and says so');

// DOC-68: --check passes on the fresh doc, fails when the code moves under it
const fresh = tool(SEAMS, ['--check', '--repo', 'web'], web, env);
ok(fresh.status === 0 && /matches the code/.test(fresh.stdout), 'DOC-68: seams --check passes on a doc that was just written');
put(path.join(web, 'public', 'app', 'c.js'), 'var z = freightTotal([3]);\n');
const stale = tool(SEAMS, ['--check', '--repo', 'web'], web, env);
ok(stale.status === 1 && /stale line/.test(stale.stdout) && /freightTotal/.test(stale.stdout), 'DOC-68: a seam used by one more file makes --check exit 1 and name the stale line');
fs.writeFileSync(doc, fs.readFileSync(doc, 'utf8').replace('<!-- GENERATED by C:/dev/seams.cjs --write.', '<!-- hand edited.'));
const lost = tool(SEAMS, ['--check', '--repo', 'web'], web, env);
ok(lost.status === 1 && /lost its GENERATED header/.test(lost.stdout), 'DOC-68: a hand-edited doc (header gone) fails --check');
fs.writeFileSync(path.join(engines, 'docs', 'SEAMS.md'), '# Seams\n\n<!-- GENERATED by C:/dev/seams.cjs --write. x -->\n');
const eng = tool(SEAMS, ['--check', '--repo', 'engines'], engines, env);
ok(eng.status === 0, 'DOC-68: engines owns no rows and passes with its header');

// DOC-68: MODULES.md has the same generate-then-check loop
const site = path.join(base, 'site');
put(path.join(site, 'tools', 'gen-modules-doc.cjs'), fs.readFileSync(MODULES, 'utf8'));
put(path.join(site, 'public', 'app.html'), '<html></html>\n');
put(path.join(site, 'public', 'app', 'alpha.js'), '/* alpha — does one thing */\nvar a = 1;\n');
const gen = tool(path.join(site, 'tools', 'gen-modules-doc.cjs'), [], site);
const checkOk = tool(path.join(site, 'tools', 'gen-modules-doc.cjs'), ['--check'], site);
ok(gen.status === 0 && checkOk.status === 0, 'DOC-68: MODULES.md --check passes right after a write');
put(path.join(site, 'public', 'app', 'beta.js'), '/* beta — another */\nvar b = 1;\n');
const checkStale = tool(path.join(site, 'tools', 'gen-modules-doc.cjs'), ['--check'], site);
ok(checkStale.status === 1, 'DOC-68: a new module file that MODULES.md does not list makes --check exit 1');

fs.rmSync(base, { recursive: true, force: true });
console.log(pass + ' passed');
