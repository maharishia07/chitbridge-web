/**
 * e2e/seams-guard.cjs — the seam index and its drift check (tools/seams.cjs, DOC-68) do what they say, on a fixture.
 *
 * OWNS      unit tests of tools/seams.cjs: scan counts the FILES that use a function, a changed count or a vanished function is a stale
 *           line, a new widely used seam is "missing", same-name files are skipped, and --check exits 1 on a drifted docs/SEAMS.md.
 * CALLED BY .github/workflows/ci.yml (web `check` job); run by hand: node e2e/seams-guard.cjs
 * FLOW      fixture web checkout in a temp folder ──▶ scan / staleOwnRows / missingFromTable ──▶ spawn --check ──▶ exit codes
 * CARD      29-qa-test-tooling-ux-locale-and-design-system/seams-index
 */
'use strict';
const assert = require('assert');
const fs = require('fs');
const os = require('os');
const path = require('path');
const { spawnSync, execFileSync } = require('child_process');

const seamsPath = path.join(__dirname, '..', 'tools', 'seams.cjs');
const seams = require(seamsPath);

let failures = 0;
/** run one named check; a throw is a red line, never a crash */
function check(name, body) {
  try {
    body();
    console.log('  \u2713 ' + name);
  } catch (error) {
    failures++;
    console.error('  \u2717 ' + name + ' - ' + error.message);
  }
}

/** a web checkout with one shared function (two callers in two files) and one private one */
function makeFixture() {
  const root = fs.mkdtempSync(path.join(os.tmpdir(), 'seams-'));
  const appDir = path.join(root, 'public', 'app');
  fs.mkdirSync(appDir, { recursive: true });
  fs.mkdirSync(path.join(root, 'docs'));
  fs.writeFileSync(path.join(root, 'public', 'app.html'), '<html></html>');
  fs.writeFileSync(path.join(appDir, 'lib-one.js'), '/** Paints the shared card for a row. */\nfunction paintSharedCard(row) { return row; }\nfunction privateHelper() { return 1; }\n');
  fs.writeFileSync(path.join(appDir, 'use-a.js'), 'paintSharedCard(1);\n');
  fs.writeFileSync(path.join(appDir, 'use-b.js'), 'paintSharedCard(2);\n');
  return root;
}

/** run the tool in a folder and return { code, out } */
function runIn(folder, args) {
  const done = spawnSync(process.execPath, [seamsPath].concat(args), { cwd: folder, encoding: 'utf8' });
  return { code: done.status, out: done.stdout };
}

console.log('\nseams.cjs (DOC-68)');
const root = makeFixture();
const rows = seams.scan([path.join(root, 'public', 'app', 'lib-one.js'), path.join(root, 'public', 'app', 'use-a.js'), path.join(root, 'public', 'app', 'use-b.js')], 'web');
const shared = rows.filter((row) => row.users.length);

check('a function used from two other files is one seam with two users; a private one has none', () => {
  assert.deepStrictEqual(shared.map((row) => row.name + ':' + row.users.length), ['paintSharedCard:2']);
  assert.ok(rows.some((row) => row.name === 'privateHelper' && row.users.length === 0));
});
check('the purpose is the first sentence of the comment above', () => assert.strictEqual(shared[0].purpose, 'Paints the shared card for a row.'));
check('a row is stale when its count changed, and when its function is gone', () => {
  const docRows = seams.tableRows(seams.rowText(shared[0]).replace('| 2 |', '| 3 |') + '\n| 1 | `vanished` | `lib-one.js` |  |');
  const stale = seams.staleOwnRows(docRows, rows, new Set());
  assert.strictEqual(stale.length, 2);
  assert.ok(/changed/.test(stale[0]) && /gone/.test(stale[1]));
});
check('a row naming a same-name file is skipped, not judged', () => {
  const docRows = seams.tableRows('| 9 | `anything` | `lib-one.js` |  |');
  assert.deepStrictEqual(seams.staleOwnRows(docRows, rows, new Set(['lib-one.js'])), []);
});
check('a seam used more widely than the table\'s weakest row but absent from it is "missing"', () => {
  const docRows = seams.tableRows('| 1 | `other` | `other.js` |  |');
  assert.strictEqual(seams.missingFromTable(docRows, shared).length, 1);
});
check('--check exits 1 on a drifted docs/SEAMS.md and 0 once the table matches', () => {
  const header = '<!-- GENERATED by C:/dev/seams.cjs --write. x -->\n<!-- same-name files in web and api (skipped): -->\n';
  const docPath = path.join(root, 'docs', 'SEAMS.md');
  fs.writeFileSync(docPath, header + '| 9 | `paintSharedCard` | `lib-one.js` | Paints the shared card for a row. |\n');
  assert.strictEqual(runIn(root, ['--check', '--repo', 'web']).code, 1);
  fs.writeFileSync(docPath, header + seams.rowText(shared[0]) + '\n');
  assert.strictEqual(runIn(root, ['--check', '--repo', 'web']).code, 0);
});
check('--check refuses a file that lost its GENERATED header', () => {
  fs.writeFileSync(path.join(root, 'docs', 'SEAMS.md'), '# hand edited\n');
  assert.strictEqual(runIn(root, ['--check', '--repo', 'engines']).code, 1);
});
check('search words must all appear; the phrase does not have to', () => {
  assert.ok(seams.matchesWords(shared[0], ['shared', 'card']));
  assert.ok(!seams.matchesWords(shared[0], ['shared', 'invoice']));
});

/** a stand-in for the shared C:/dev folder: an api checkout whose origin/main has one function used twice and whose working copy is stale-different */
function makeSharedDir() {
  const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'seams-shared-'));
  const api = path.join(dir, 'chitbridge-api');
  fs.mkdirSync(path.join(api, 'lib'), { recursive: true });
  fs.mkdirSync(path.join(api, 'docs'));
  fs.writeFileSync(path.join(api, 'docs', 'SEAMS.md'), 'SENTINEL\n');
  fs.writeFileSync(path.join(api, 'lib', 'a.js'), 'function apiOriginMainThing() { return 1; }\n');
  fs.writeFileSync(path.join(api, 'lib', 'b.js'), 'apiOriginMainThing();\n');
  const git = (args) => execFileSync('git', ['-C', api].concat(args), { stdio: 'ignore' });
  git(['init', '-q']); git(['add', 'lib']);
  git(['-c', 'user.name=t', '-c', 'user.email=t@t', 'commit', '-qm', 'x']);
  git(['update-ref', 'refs/remotes/origin/main', 'HEAD']);
  fs.writeFileSync(path.join(api, 'lib', 'a.js'), 'function staleWorkingCopyThing() { return 1; }\n');
  return { dir, api };
}

check('--write writes only the docs/SEAMS.md of the repo it runs from, and reads the sibling from origin/main, not its working copy', () => {
  const { dir, api } = makeSharedDir();
  const before = fs.readdirSync(dir, { recursive: true }).filter((name) => !/(^|[\/]).git/.test(name)).map((name) => name + ':' + fs.statSync(path.join(dir, name)).mtimeMs).join('|');
  const done = spawnSync(process.execPath, [seamsPath, '--write'], { cwd: root, encoding: 'utf8', env: Object.assign({}, process.env, { SEAMS_SHARED_DIR: dir }) });
  assert.strictEqual(done.status, 0, done.stderr);
  const written = fs.readFileSync(path.join(root, 'docs', 'SEAMS.md'), 'utf8');
  assert.ok(written.includes('apiOriginMainThing') && !written.includes('staleWorkingCopyThing'), 'sibling must come from origin/main');
  assert.strictEqual(fs.readFileSync(path.join(api, 'docs', 'SEAMS.md'), 'utf8'), 'SENTINEL\n');
  assert.strictEqual(fs.readdirSync(dir, { recursive: true }).filter((name) => !/(^|[\/]).git/.test(name)).map((name) => name + ':' + fs.statSync(path.join(dir, name)).mtimeMs).join('|'), before, 'the shared folder changed');
  fs.rmSync(dir, { recursive: true, force: true });
});
check('--write from a folder that is not a repo root refuses with one line and exit 1', () => {
  const empty = fs.mkdtempSync(path.join(os.tmpdir(), 'seams-empty-'));
  const done = runIn(empty, ['--write']);
  assert.strictEqual(done.code, 1);
  assert.strictEqual(done.out.trim().split('\n').length, 1);
  fs.rmSync(empty, { recursive: true, force: true });
});

fs.rmSync(root, { recursive: true, force: true });
if (failures) {
  console.error('\nseams-guard: ' + failures + ' failed\n');
  process.exit(1);
}
console.log('\nseams-guard: all passed\n');
